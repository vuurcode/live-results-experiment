export function format(text: string, params?: Record<string, string | number>): string {
  return params ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : text;
}

export function dtsText(lang: DtsLang, key: DtsKey, params?: Record<string, string | number>): string {
  return format((lang === 'nl' ? nl : en)[key], params);
}

/** Dutch unless English was chosen, whatever language the browser is in. */
export function initialLang(stored: string | null): DtsLang {
  return stored === 'en' ? 'en' : 'nl';
}
